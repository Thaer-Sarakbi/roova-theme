#!/usr/bin/env bash
#
# Run the theme on a real WordPress + WooCommerce site on Windows, from Git Bash.
#
# The macOS script (bin/testenv.sh) expects Homebrew php and mariadb. Windows
# usually has neither, so this one downloads a portable PHP and MariaDB into
# .testenv/ and runs everything out of that directory. Nothing is installed
# system-wide and nothing is added to PATH.
#
# Usage:
#   bin/testenv-win.sh            # start it (installing whatever is missing)
#   bin/testenv-win.sh stop       # stop the web server and the database
#   bin/testenv-win.sh status     # what is running, and on which ports
#   bin/testenv-win.sh restart
#   bin/testenv-win.sh fresh      # wipe the site + database, reinstall, re-seed
#   bin/testenv-win.sh seed       # re-create the demo hotels, rooms and terms
#   bin/testenv-win.sh wp <args>  # run wp-cli against the site
#
# The theme is linked into the site with a directory junction, so edits to
# roova/ are live on the next page load — there is no build or copy step.
#
# .testenv/ is disposable and gitignored: delete it to start completely over.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENVDIR="$ROOT/.testenv"
SITE="$ENVDIR/site"
DL="$ENVDIR/dl"
PHP="$ENVDIR/php/php.exe"
MARIADB="$ENVDIR/mariadb"
DATA="$ENVDIR/mysql-data"

PORT="${ROOVA_PORT:-8099}"
DB_PORT="${ROOVA_DB_PORT:-3307}"
DB_NAME=roova_test

PHP_ZIP_URL="https://downloads.php.net/~windows/releases/php-8.3.33-nts-Win32-vs16-x64.zip"
MARIADB_ZIP_URL="https://archive.mariadb.org/mariadb-10.11.11/winx64-packages/mariadb-10.11.11-winx64.zip"
WP_ZIP_URL="https://wordpress.org/latest.zip"
WC_ZIP_URL="https://downloads.wordpress.org/plugin/woocommerce.latest-stable.zip"
WPCLI_URL="https://raw.githubusercontent.com/wp-cli/builds/gh-pages/phar/wp-cli.phar"

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }

win() { cygpath -w "$1"; }

wp() { "$PHP" "$DL/wp-cli.phar" --path="$(win "$SITE")" "$@"; }

mysql_cmd() { "$MARIADB/bin/mysql.exe" --protocol=tcp -h 127.0.0.1 -P "$DB_PORT" "$@"; }

db_running() {
	"$MARIADB/bin/mysqladmin.exe" --protocol=tcp -h 127.0.0.1 -P "$DB_PORT" -u root ping >/dev/null 2>&1
}

web_running() {
	curl -sS -o /dev/null --max-time 5 "http://127.0.0.1:$PORT/" 2>/dev/null
}

# ---------------------------------------------------------------- downloads

fetch() {
	local url="$1" out="$2"
	[ -s "$out" ] && return 0
	echo "  downloading $(basename "$out")…"
	curl -sSL -o "$out" "$url"
}

download_all() {
	mkdir -p "$DL"
	fetch "$PHP_ZIP_URL" "$DL/php.zip"
	fetch "$MARIADB_ZIP_URL" "$DL/mariadb.zip"
	fetch "$WP_ZIP_URL" "$DL/wordpress.zip"
	fetch "$WC_ZIP_URL" "$DL/woocommerce.zip"
	fetch "$WPCLI_URL" "$DL/wp-cli.phar"
}

# ------------------------------------------------------------------- tools

install_php() {
	[ -x "$PHP" ] && return 0
	say "Unpacking PHP"
	mkdir -p "$ENVDIR/php"
	unzip -q "$DL/php.zip" -d "$ENVDIR/php"

	cat > "$ENVDIR/php/php.ini" <<-'INI'
		extension_dir = "ext"
		extension=mysqli
		extension=mbstring
		extension=gd
		extension=curl
		extension=openssl
		extension=zip
		extension=exif
		extension=fileinfo
		extension=sodium

		memory_limit = 512M
		upload_max_filesize = 64M
		post_max_size = 64M
		max_execution_time = 120
		date.timezone = UTC
		display_errors = On
		error_reporting = E_ALL & ~E_DEPRECATED
	INI

	"$PHP" -v | head -1
}

install_mariadb() {
	[ -x "$MARIADB/bin/mariadbd.exe" ] && return 0
	say "Unpacking MariaDB"
	unzip -q "$DL/mariadb.zip" -d "$ENVDIR"
	mv "$ENVDIR"/mariadb-*-winx64 "$MARIADB"
}

write_router() {
	cat > "$ENVDIR/router.php" <<-'PHP'
		<?php
		/**
		 * Router for `php -S`: serve real files (assets, wp-admin scripts) directly
		 * and hand everything else to WordPress so pretty permalinks work.
		 *
		 * Generated by bin/testenv-win.sh — edits here are overwritten.
		 */

		$root = __DIR__ . '/site';
		$path = parse_url( $_SERVER['REQUEST_URI'], PHP_URL_PATH );
		$file = $root . urldecode( $path );

		if ( '/' !== $path && is_file( $file ) ) {
			return false;
		}

		if ( is_dir( $file ) && is_file( rtrim( $file, '/' ) . '/index.php' ) ) {
			require rtrim( $file, '/' ) . '/index.php';
			return true;
		}

		require $root . '/index.php';
	PHP
}

# ---------------------------------------------------------------- database

start_db() {
	if db_running; then
		return 0
	fi

	if [ ! -d "$DATA" ]; then
		say "Initialising the database"
		"$MARIADB/bin/mariadb-install-db.exe" --datadir="$(win "$DATA")" >/dev/null
	fi

	say "Starting MariaDB on port $DB_PORT"
	nohup "$MARIADB/bin/mariadbd.exe" \
		--datadir="$(win "$DATA")" \
		--port="$DB_PORT" \
		--bind-address=127.0.0.1 \
		--skip-name-resolve \
		--console >"$ENVDIR/mysqld.log" 2>&1 &
	echo $! > "$ENVDIR/mysqld.pid"

	for _ in $(seq 1 40); do
		db_running && break
		sleep 1
	done

	db_running || { echo "MariaDB did not start — see .testenv/mysqld.log" >&2; exit 1; }
}

create_db() {
	mysql_cmd -u root -e "
		CREATE DATABASE IF NOT EXISTS $DB_NAME;
		CREATE USER IF NOT EXISTS 'roova'@'%' IDENTIFIED BY 'roova';
		GRANT ALL ON $DB_NAME.* TO 'roova'@'%';
		FLUSH PRIVILEGES;"
}

# --------------------------------------------------------------- wordpress

link_theme() {
	local target="$SITE/wp-content/themes/roova"

	# A junction needs no admin rights and makes the working tree live.
	if [ ! -e "$target" ]; then
		cmd //c mklink //J "$(win "$target")" "$(win "$ROOT/roova")" >/dev/null 2>&1 \
			|| cp -r "$ROOT/roova" "$target"
	fi
}

install_wordpress() {
	if [ -f "$SITE/wp-config.php" ] && wp core is-installed >/dev/null 2>&1; then
		link_theme
		return 0
	fi

	say "Installing WordPress"
	rm -rf "$SITE"
	mkdir -p "$SITE"
	unzip -q "$DL/wordpress.zip" -d "$ENVDIR"
	mv "$ENVDIR/wordpress"/* "$SITE"/
	rmdir "$ENVDIR/wordpress"

	wp core config --dbname="$DB_NAME" --dbuser=roova --dbpass=roova \
		--dbhost="127.0.0.1:$DB_PORT" --skip-check --extra-php <<-'PHP'
		define( 'WP_DEBUG', true );
		define( 'WP_DEBUG_DISPLAY', true );
		define( 'FS_METHOD', 'direct' );
	PHP

	wp core install --url="http://127.0.0.1:$PORT" --title="Roova Test" \
		--admin_user=admin --admin_password=admin \
		--admin_email=test@example.com --skip-email

	say "Installing WooCommerce"
	wp plugin install "$(win "$DL/woocommerce.zip")" --activate

	# WooCommerce hides the whole store behind a "coming soon" page on a fresh
	# install, which makes hotel pages look broken.
	wp option update woocommerce_coming_soon no

	# Cash on delivery, so checkout can complete without a payment gateway.
	wp eval '$s = get_option( "woocommerce_cod_settings", array() ); $s["enabled"] = "yes"; update_option( "woocommerce_cod_settings", $s );'

	link_theme
	wp theme activate roova
	wp rewrite structure '/%postname%/' >/dev/null
	wp option update blog_public 0 >/dev/null

	seed
}

seed() {
	say "Seeding demo hotels, rooms, destinations, amenities and facilities"
	wp eval-file "$(win "$ROOT/bin/testenv-seed.php")" 2>&1 | grep -v '^Deprecated:' || true
}

# ------------------------------------------------------------- web server

start_web() {
	if web_running; then
		echo "Web server already up on $PORT."
		return 0
	fi

	write_router
	say "Starting the web server on port $PORT"
	nohup "$PHP" -S "127.0.0.1:$PORT" -t "$(win "$SITE")" "$(win "$ENVDIR/router.php")" \
		>"$ENVDIR/php-server.log" 2>&1 &
	echo $! > "$ENVDIR/php-server.pid"

	for _ in $(seq 1 20); do
		web_running && break
		sleep 1
	done
}

stop_one() {
	local pidfile="$1" name="$2"
	[ -f "$pidfile" ] || return 0
	local pid
	pid="$(cat "$pidfile")"
	if kill "$pid" 2>/dev/null || kill -f "$pid" 2>/dev/null; then
		echo "stopped $name (pid $pid)"
	fi
	rm -f "$pidfile"
}

# -------------------------------------------------------------- commands

cmd_up() {
	download_all
	install_php
	install_mariadb
	start_db
	create_db
	install_wordpress
	start_web

	say "Ready"
	cat <<-INFO
	  Site       http://127.0.0.1:$PORT
	  Admin      http://127.0.0.1:$PORT/wp-admin  (admin / admin)
	  Theme      linked live from roova/ — just reload the page after an edit
	  Database   127.0.0.1:$DB_PORT  ($DB_NAME, roova/roova)
	  Stop       bin/testenv-win.sh stop
	INFO
}

cmd_stop() {
	stop_one "$ENVDIR/php-server.pid" "web server"
	stop_one "$ENVDIR/mysqld.pid" "database"
	if db_running; then
		"$MARIADB/bin/mysqladmin.exe" --protocol=tcp -h 127.0.0.1 -P "$DB_PORT" -u root shutdown >/dev/null 2>&1 || true
	fi
}

cmd_status() {
	if web_running; then
		echo "web server  UP    http://127.0.0.1:$PORT"
	else
		echo "web server  down"
	fi
	if db_running; then
		echo "database    UP    127.0.0.1:$DB_PORT"
	else
		echo "database    down"
	fi
	if [ -d "$SITE" ]; then
		echo "site        $SITE"
	else
		echo "site        not installed"
	fi
}

cmd_fresh() {
	cmd_stop
	say "Wiping the site and database"
	rm -rf "$SITE"
	start_db
	mysql_cmd -u root -e "DROP DATABASE IF EXISTS $DB_NAME;"
	cmd_up
}

case "${1:-up}" in
	up|start)  cmd_up ;;
	stop|down) cmd_stop ;;
	restart)   cmd_stop; cmd_up ;;
	status)    cmd_status ;;
	fresh)     cmd_fresh ;;
	seed)      seed ;;
	wp)        shift; wp "$@" ;;
	*)         sed -n '3,30p' "${BASH_SOURCE[0]}"; exit 1 ;;
esac
